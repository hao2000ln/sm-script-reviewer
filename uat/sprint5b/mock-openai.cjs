'use strict';

const { createServer } = require('node:http');

const port = Number(process.env.SM_REVIEWER_MOCK_PORT || 8787);
if (!Number.isSafeInteger(port) || port < 1 || port > 65535) {
  console.error('SM_REVIEWER_MOCK_PORT must be an integer from 1 to 65535.');
  process.exitCode = 2;
  return;
}

const server = createServer(async (request, response) => {
  const url = new URL(request.url || '/', 'http://127.0.0.1');
  if (request.method !== 'POST' || url.pathname !== '/v1/chat/completions') {
    return send(response, 404, { error: { message: 'Mock endpoint not found' } });
  }
  if (url.searchParams.get('scenario') === '429') {
    return send(response, 429, { error: { message: 'Deterministic mock rate limit' } });
  }
  try {
    let body = '';
    for await (const chunk of request) body += String(chunk);
    const payload = JSON.parse(body);
    const context = JSON.parse(payload.messages?.[1]?.content || '{}').context;
    if (!context?.source || !context?.snippet?.range) throw new Error('Missing AI review context');
    return send(response, 200, {
      choices: [{ message: { content: JSON.stringify({ findings: [mockFinding(context, payload.model)] }) } }],
    });
  } catch {
    return send(response, 400, { error: { message: 'Mock could not parse AI review request' } });
  }
});

server.listen(port, '127.0.0.1', () => {
  console.log(`SM Reviewer mock AI server listening at http://127.0.0.1:${port}/v1/chat/completions`);
  console.log(`Rate-limit scenario: http://127.0.0.1:${port}/v1/chat/completions?scenario=429`);
  console.log('Press Ctrl+C to stop. No external network calls are made.');
});

function mockFinding(context, modelId) {
  return {
    id: 'ai:manual-mock:1', sourceId: context.source.id, sourceHash: context.source.hash,
    range: context.snippet.range, category: 'maintainability', severity: 'warning',
    message: 'Local mock AI observation', explanation: 'Generated by localhost-only manual UAT.',
    suggestion: 'Verify this model-generated observation manually.', evidenceReferences: ['source:target'],
    confidence: 0.7, assertionKind: 'model-inference',
    model: { providerId: 'manual-localhost-mock', modelId: modelId || 'mock-model' },
    validationStatus: 'unvalidated',
  };
}

function send(response, status, value) {
  const body = JSON.stringify(value);
  response.writeHead(status, { 'content-type': 'application/json', 'content-length': Buffer.byteLength(body) });
  response.end(body);
}

for (const signal of ['SIGINT', 'SIGTERM']) {
  process.on(signal, () => server.close(() => process.exit(0)));
}
